#!/usr/bin/env bash
set -euo pipefail

if [[ "$#" -gt 0 ]]; then
  echo "Error: train_pi05_libero_calibrated_pytorch.sh only accepts environment variables; got positional args: $*" >&2
  exit 2
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

VISION_ROUTER_CALIBRATION_SOURCE="${VISION_ROUTER_CALIBRATION_SOURCE:-vit}"
case "$VISION_ROUTER_CALIBRATION_SOURCE" in
  vit|vlm|action) ;;
  *)
    echo "Error: invalid VISION_ROUTER_CALIBRATION_SOURCE '$VISION_ROUTER_CALIBRATION_SOURCE' (expected vit|vlm|action)" >&2
    exit 2
    ;;
esac

CONFIG_NAME="${CONFIG_NAME:-pi05_libero}"
EXP_NAME="${EXP_NAME:-${CONFIG_NAME}_${VISION_ROUTER_CALIBRATION_SOURCE}_calibrated}"
GPU_IDS="${GPU_IDS:-0,1,2,3}"
CALIBRATION_GPU_ID="${CALIBRATION_GPU_ID:-${GPU_IDS%%,*}}"
NPROC_PER_NODE="${NPROC_PER_NODE:-4}"
BATCH_SIZE="${BATCH_SIZE:-256}"
NUM_TRAIN_STEPS="${NUM_TRAIN_STEPS:-30000}"
SAVE_INTERVAL="${SAVE_INTERVAL:-5000}"
LOG_INTERVAL="${LOG_INTERVAL:-100}"
NUM_WORKERS="${NUM_WORKERS:-2}"
SEED="${SEED:-42}"

CALIBRATION_CHECKPOINT_DIR="${CALIBRATION_CHECKPOINT_DIR:-$REPO_ROOT/models/pi05_libero_pytorch}"
PYTORCH_WEIGHT_PATH="${PYTORCH_WEIGHT_PATH:-$CALIBRATION_CHECKPOINT_DIR}"

VISION_ROUTER_ATTENTION_COVERAGE="${VISION_ROUTER_ATTENTION_COVERAGE:-0.8}"
VISION_ROUTER_GLOBAL_COVERAGE_UPPER="${VISION_ROUTER_GLOBAL_COVERAGE_UPPER:-0.9}"
VISION_ROUTER_BUDGET_QUANTILE="${VISION_ROUTER_BUDGET_QUANTILE:-0.95}"
VISION_ROUTER_TOKEN_ALIGNMENT="${VISION_ROUTER_TOKEN_ALIGNMENT:-32}"
VISION_ROUTER_GLOBAL_MIN_TOKENS="${VISION_ROUTER_GLOBAL_MIN_TOKENS:-64}"

CALIBRATION_NUM_SAMPLES="${CALIBRATION_NUM_SAMPLES:-1024}"
CALIBRATION_BATCH_SIZE="${CALIBRATION_BATCH_SIZE:-2}"
CALIBRATION_NUM_WORKERS="${CALIBRATION_NUM_WORKERS:-0}"

OUTPUTS_BASE_DIR="${OUTPUTS_BASE_DIR:-$REPO_ROOT/outputs}"
RUN_OUTPUT_DIR="${RUN_OUTPUT_DIR:-$OUTPUTS_BASE_DIR/$CONFIG_NAME/$EXP_NAME}"
CHECKPOINT_BASE_DIR="${CHECKPOINT_BASE_DIR:-$REPO_ROOT/checkpoints}"
CHECKPOINT_DIR="$CHECKPOINT_BASE_DIR/$CONFIG_NAME/$EXP_NAME"
ASSETS_BASE_DIR="${ASSETS_BASE_DIR:-$REPO_ROOT/assets}"
PYTHON_BIN="${PYTHON_BIN:-$REPO_ROOT/.venv/bin/python}"
WANDB_DIR="${WANDB_DIR:-$RUN_OUTPUT_DIR}"
WANDB_MODE="${WANDB_MODE:-offline}"
WANDB_ENABLED="${WANDB_ENABLED:-true}"
DRY_RUN="${DRY_RUN:-0}"

CALIBRATION_DIR="$RUN_OUTPUT_DIR/calibration"
BUDGET_JSON="$CALIBRATION_DIR/token_budget_${VISION_ROUTER_CALIBRATION_SOURCE}.json"
BUDGET_NPZ="$CALIBRATION_DIR/token_budget_${VISION_ROUTER_CALIBRATION_SOURCE}.npz"
CALIBRATION_LOG="$RUN_OUTPUT_DIR/calibration.log"
TRAIN_LOG="$RUN_OUTPUT_DIR/train.log"

if [[ -e "$RUN_OUTPUT_DIR" ]]; then
  echo "Error: RUN_OUTPUT_DIR already exists, refusing to overwrite: $RUN_OUTPUT_DIR" >&2
  exit 2
fi

if [[ -e "$CHECKPOINT_DIR" ]]; then
  echo "Error: CHECKPOINT_DIR already exists, refusing to overwrite: $CHECKPOINT_DIR" >&2
  exit 2
fi

CALIBRATE_CMD=(
  "$PYTHON_BIN" "$SCRIPT_DIR/calibrate_token_budget.py"
  "--config-name" "$CONFIG_NAME"
  "--checkpoint-dir" "$CALIBRATION_CHECKPOINT_DIR"
  "--output-dir" "$CALIBRATION_DIR"
  "--attention-source" "$VISION_ROUTER_CALIBRATION_SOURCE"
  "--num-samples" "$CALIBRATION_NUM_SAMPLES"
  "--batch-size" "$CALIBRATION_BATCH_SIZE"
  "--num-workers" "$CALIBRATION_NUM_WORKERS"
  "--seed" "$SEED"
  "--coverage-target" "$VISION_ROUTER_ATTENTION_COVERAGE"
  "--sample-quantile" "$VISION_ROUTER_BUDGET_QUANTILE"
  "--alignment" "$VISION_ROUTER_TOKEN_ALIGNMENT"
  "--global-coverage-upper" "$VISION_ROUTER_GLOBAL_COVERAGE_UPPER"
  "--global-min-tokens" "$VISION_ROUTER_GLOBAL_MIN_TOKENS"
  "--assets-base-dir" "$ASSETS_BASE_DIR"
)

if [[ "$DRY_RUN" == "1" || "$DRY_RUN" == "true" ]]; then
  echo "[DRY_RUN] CONFIG_NAME=$CONFIG_NAME"
  echo "[DRY_RUN] EXP_NAME=$EXP_NAME"
  echo "[DRY_RUN] GPU_IDS=$GPU_IDS (calibration GPU=$CALIBRATION_GPU_ID, nproc=$NPROC_PER_NODE)"
  echo "[DRY_RUN] CALIBRATION_CHECKPOINT_DIR=$CALIBRATION_CHECKPOINT_DIR"
  echo "[DRY_RUN] PYTORCH_WEIGHT_PATH=$PYTORCH_WEIGHT_PATH"
  echo "[DRY_RUN] SOURCE=$VISION_ROUTER_CALIBRATION_SOURCE COVERAGE=$VISION_ROUTER_ATTENTION_COVERAGE UPPER=$VISION_ROUTER_GLOBAL_COVERAGE_UPPER QUANTILE=$VISION_ROUTER_BUDGET_QUANTILE ALIGNMENT=$VISION_ROUTER_TOKEN_ALIGNMENT GLOBAL_MIN=$VISION_ROUTER_GLOBAL_MIN_TOKENS"
  echo "[DRY_RUN] RUN_OUTPUT_DIR=$RUN_OUTPUT_DIR"
  echo "[DRY_RUN] CHECKPOINT_DIR=$CHECKPOINT_DIR"
  echo "[DRY_RUN] BUDGET_JSON=$BUDGET_JSON"
  echo "[DRY_RUN] CALIBRATE_CMD: CUDA_VISIBLE_DEVICES=$CALIBRATION_GPU_ID ${CALIBRATE_CMD[*]}"
  echo "[DRY_RUN] TRAIN_CMD: VISION_ROUTER_BUDGET_PATH=$BUDGET_JSON bash $SCRIPT_DIR/train_pi05_libero_vision_router_pytorch.sh"
  exit 0
fi

if [[ ! -x "$PYTHON_BIN" ]]; then
  echo "Error: PYTHON_BIN is not executable: $PYTHON_BIN" >&2
  exit 2
fi

if [[ ! -e "$CALIBRATION_CHECKPOINT_DIR" ]]; then
  echo "Error: CALIBRATION_CHECKPOINT_DIR does not exist: $CALIBRATION_CHECKPOINT_DIR" >&2
  exit 2
fi

if [[ ! -e "$PYTORCH_WEIGHT_PATH" ]]; then
  echo "Error: PYTORCH_WEIGHT_PATH does not exist: $PYTORCH_WEIGHT_PATH" >&2
  exit 2
fi

mkdir -p "$CALIBRATION_DIR" "$WANDB_DIR/wandb"

CUDA_VISIBLE_DEVICES="$CALIBRATION_GPU_ID" \
JAX_PLATFORMS="${JAX_PLATFORMS:-cpu}" \
"${CALIBRATE_CMD[@]}" 2>&1 | tee "$CALIBRATION_LOG"

if [[ ! -s "$BUDGET_JSON" || ! -s "$BUDGET_NPZ" ]]; then
  echo "Error: calibration did not produce expected artifacts: $BUDGET_JSON and $BUDGET_NPZ" >&2
  exit 2
fi

export CONFIG_NAME
export EXP_NAME
export GPU_IDS
export NPROC_PER_NODE
export BATCH_SIZE
export NUM_TRAIN_STEPS
export SAVE_INTERVAL
export LOG_INTERVAL
export NUM_WORKERS
export SEED
export RUN_MODE="overwrite"
export HARD_ENABLED="true"
export SOFT_ENABLED="true"
export PYTORCH_WEIGHT_PATH
export CHECKPOINT_BASE_DIR
export ASSETS_BASE_DIR
export PYTHON_BIN
export WANDB_DIR
export WANDB_MODE
export WANDB_ENABLED
export RUN_OUTPUT_DIR
export VISION_ROUTER_BUDGET_PATH="$BUDGET_JSON"
export VISION_ROUTER_CALIBRATION_SOURCE
export VISION_ROUTER_ATTENTION_COVERAGE
export VISION_ROUTER_BUDGET_QUANTILE
export VISION_ROUTER_GLOBAL_COVERAGE_UPPER
export VISION_ROUTER_GLOBAL_MIN_TOKENS
export VISION_ROUTER_TOKEN_ALIGNMENT

bash "$SCRIPT_DIR/train_pi05_libero_vision_router_pytorch.sh" 2>&1 | tee "$TRAIN_LOG"

cat > "$RUN_OUTPUT_DIR/run_status.json" <<EOF
{
  "status": "completed",
  "config_name": "$CONFIG_NAME",
  "exp_name": "$EXP_NAME",
  "attention_source": "$VISION_ROUTER_CALIBRATION_SOURCE",
  "budget_json": "$BUDGET_JSON",
  "budget_npz": "$BUDGET_NPZ",
  "checkpoint_dir": "$CHECKPOINT_DIR",
  "num_train_steps": $NUM_TRAIN_STEPS
}
EOF
